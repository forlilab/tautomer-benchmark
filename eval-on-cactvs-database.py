def myeval(input_mol, target_mols, tautomer_generator_func):

    predicted_tautomers = tautomer_generator_func(input_mol)
    missed_targets = []
    excess_tautomers = []

    target_smiles_list = []
    for mol in target_mols:
        smiles = Chem.MolToSmiles(Chem.MolFromSmiles(Chem.MolToSmiles(mol)), isomericSmiles=False)
        target_smiles_list.append(smiles)

    input_smiles = Chem.MolToSmiles(Chem.MolFromSmiles(Chem.MolToSmiles(input_mol)), isomericSmiles=False)
    target_smiles_list = [s for s in list(set(target_smiles_list)) if s != input_smiles]
    hit_mask = [False for _ in target_smiles_list]
    for t in predicted_tautomers:
        pred_smiles = Chem.MolToSmiles(Chem.RemoveHs(t), isomericSmiles=False)
        matched = False
        for i, target_smiles in enumerate(target_smiles_list):
            hit_mask[i] = hit_mask[i] or (smiles == pred_smiles)
            matched = matched or (smiles == pred_smiles)
        if not matched:
            excess_tautomers.append(pred_smiles)

    for i in range(len(hit_mask)):
        if hit_mask[i] == False:
           missed_targets.append(target_smiles_list[i])

    n_hits = sum(hit_mask)
    n_misses = len(hit_mask) - n_hits
    n_tautomers_generated = len(predicted_tautomers)
    return n_hits, n_misses, n_tautomers_generated, missed_targets, excess_tautomers


